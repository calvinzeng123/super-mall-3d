// Text form of the generated plan-data files: one line per unit / home keeps them diffable.
// Shared by scripts/plans/{west,north}.mjs (and later r-penthouse.mjs); owned by the driver.
export const HEADER = '// Generated by scripts/prepare-community-plans.mjs; do not hand-edit.';
const j = (v) => JSON.stringify(v);
const tower = (T, key) => { const { [key]: list, ...rest } = T; return `${j(rest).slice(0, -1)},${j(key)}:[\n${list.map(j).join(',\n')}\n]}`; };
/** `    id: {…,"key":[\n…\n]}` lines for every tower, joined by ',\n'. */
export const section = (towers, key) => Object.entries(towers).map(([id, T]) => `    ${id}: ${tower(T, key)}`).join(',\n');
/** A whole data file exporting `name` = { tower id: tower record }. */
export const dataFile = (comment, name, towers, key) => `${HEADER}
// ${comment}
export const ${name} = {
${section(towers, key)},
};
`;
