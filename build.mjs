// 生成三个产物：
//   index.html          开发版，直接引用 ./src/main.js（需本地 http 服务）
//   dist/artifact.html  发布片段（无 doctype/head/body，供 Artifact 包装）
//   dist/mall.html      完整单文件页面，可双击打开
import { build } from 'esbuild';
import { execSync } from 'node:child_process';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { FPS_MODEL_ASSETS } from './src/fps/model-data.js';
import { geometryLicenses } from './scripts/geometry-licenses.mjs';
import { TITLE_FALLBACK } from './src/title/fallback-data.js';
import { packProps } from './scripts/props/pack.mjs';
import { bake as bakeTitle } from './scripts/title/bake.mjs';

// 开场资源（楼型、预画丧尸贴图、子集字体）：输入没变就用上次的产物，见 scripts/title/bake.mjs
const titleAssets = await bakeTitle();
const shell = await readFile('src/shell.html', 'utf8');
if (!shell.includes('<!--APP-->')) throw new Error('src/shell.html 缺少 <!--APP--> 占位');

const manifest = JSON.parse(await readFile('assets/textures/manifest.json', 'utf8'));
// 第二批 CC0 扫描贴图（Poly Haven、ambientCG；scripts/textures/fetch-scans.py 下载处理）同样嵌入、同样加载。
const scans = JSON.parse(await readFile('assets/textures/scans/manifest.json', 'utf8'));
const surfaces = await Promise.all([...manifest.assets, ...scans.assets].map(async (asset) => ({
  id: asset.id, meters: asset.meters, sourceUrl: asset.sourceUrl || null, mean: asset.meanColor || null,
  maps: Object.fromEntries(await Promise.all(Object.entries(asset.maps).map(async ([key, map]) =>
    [key, `data:image/jpeg;base64,${(await readFile(map.path)).toString('base64')}`]))),
})));
await writeFile('src/render/pbr-data.js', '// Generated by build.mjs from CC0 source assets (assets/textures).\nexport const SURFACE_ASSETS = ' + JSON.stringify(surfaces) + ';\n');
const peopleManifest = JSON.parse(await readFile('assets/models/people/manifest.json', 'utf8'));
const peopleAssets = await Promise.all(peopleManifest.models.map(async model => ({
  id: model.id, name: model.name, poses: model.poses, cycleSeconds: model.cycleSeconds,
  license: 'MIT', url: `data:model/gltf-binary;base64,${(await readFile(`assets/models/people/${model.file}`)).toString('base64')}`,
})));
await writeFile('src/render/people-data.js', '// Generated from MIT Microsoft Rocketbox models.\nexport const PEOPLE_ASSETS = ' + JSON.stringify(peopleAssets) + ';\n');
const suiteBytes = await readFile('assets/models/user-suite-processed.glb');
await writeFile('src/render/suite-data.js', '// Generated by build.mjs from the user suite model.\nexport const SUITE_MODEL_URL = ' + JSON.stringify(`data:model/gltf-binary;base64,${suiteBytes.toString('base64')}`) + ';\n');

// Preserve the original Blender exports byte-for-byte. Compression only changes
// their transport in the offline page; the loader still receives the same GLBs.
const residentialAssets = [];
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
for (const unit of ['01', '02', '03']) {
  const plan = JSON.parse(await readFile(`scripts/residential/plan_${unit}.json`, 'utf8'));
  const basename = plan.model_basename || `云澜汇_${unit}${unit === '03' ? '四' : '三'}房两厅`;
  const bytes = await readFile(`prototypes/residential${unit}/${basename}.glb`);
  if (bytes.readUInt32LE(0) !== 0x46546c67 || bytes.readUInt32LE(8) !== bytes.length) throw new Error(`住宅${unit} GLB不完整`);
  const jsonLength = bytes.readUInt32LE(12);
  const definition = JSON.parse(bytes.subarray(20, 20 + jsonLength).toString('utf8'));
  const binaryStart = 20 + jsonLength + 8;
  const imageHashes = definition.images.map(image => {
    const view = definition.bufferViews[image.bufferView];
    if (!view) throw new Error(`住宅${unit}包含非内嵌图片`);
    return sha256(bytes.subarray(binaryStart + (view.byteOffset || 0), binaryStart + (view.byteOffset || 0) + view.byteLength));
  });
  const compressed = gzipSync(bytes, { level: 6 });
  residentialAssets.push({ unit, compression: 'gzip', data: compressed.toString('base64'),
    modelFile: `${basename}.glb`, modelSHA256: sha256(bytes), modelBytes: bytes.length,
    compressedBytes: compressed.length, compressedSHA256: sha256(compressed), imageHashes,
    textureSources: definition.textures.map(texture => texture.source),
    width: plan.envelope.outer_rect[2], depth: plan.envelope.outer_rect[3], ceiling: plan.envelope.ceiling_z,
    lighting: plan.viewer?.lighting || null });
}
await writeFile('src/render/residential-data.js', '// Generated by build.mjs from the original residential GLBs. Do not edit.\nexport const RESIDENTIAL_ASSETS = ' + JSON.stringify(residentialAssets) + ';\n');

await writeFile('index.html', wrap(shell.replace('<!--APP-->', '<script type="module" src="./src/main.js"></script>')));

const embeddedFPS = await Promise.all(FPS_MODEL_ASSETS.map(async a=>({...a,url:`data:model/gltf-binary;base64,${(await readFile(a.url.replace(/^\.\//,''))).toString('base64')}`})));
// 贴图小模型：所有 GLB 首尾相接打成一包，内嵌成一段 base64。
const props = await packProps();
const propModule = `export const PROP_ASSETS = ${JSON.stringify(props.assets)};\nexport const PROP_PACK = ${JSON.stringify({ url: `data:application/octet-stream;base64,${props.bytes.toString('base64')}` })};`;
// HDR 天空素材（两个小文件，约 210 KB）：内嵌成 data: 地址。
const skyModule = `export const SKY_ASSETS = ${JSON.stringify({
  radiance: `data:application/octet-stream;base64,${(await readFile('assets/sky/day-radiance.hdr')).toString('base64')}`,
  photo: `data:image/jpeg;base64,${(await readFile('assets/sky/day-sky.jpg')).toString('base64')}`,
})};`;
// 开场资源内嵌成 data: 地址（单文件版不受加载预算约束）
const dataURL = async (url, mime) => `data:${mime};base64,${(await readFile(url.replace(/^\.\//, ''))).toString('base64')}`;
const titleModule = `export const TITLE_TOWERS = ${JSON.stringify(titleAssets.towers)};\n`
  + `export const TITLE_ZOMBIE_TEX = ${JSON.stringify(await Promise.all(titleAssets.zombies.map(async (e) => ({ ...e, url: await dataURL(e.url, 'image/jpeg') }))))};\n`
  + `export const TITLE_PEOPLE = ${JSON.stringify(await Promise.all(titleAssets.people.map(async (m) => ({ ...m, url: await dataURL(m.url, 'model/gltf-binary') }))))};\n`
  + `export const TITLE_FONTS = ${JSON.stringify(Object.fromEntries(await Promise.all(Object.entries(titleAssets.fonts).map(async ([k, u]) => [k, await dataURL(u, 'font/woff2')]))))};\n`
  + `export const TITLE_FONT_FAMILIES = ${JSON.stringify(titleAssets.families)};\n`;
// 首页兜底素材（静态主视觉、静态 Logo）：单文件版也内嵌，断网、没有 WebGL 时照样有画面
const fallbackModule = `export const TITLE_FALLBACK = ${JSON.stringify({ scene: await dataURL(TITLE_FALLBACK.scene, 'image/jpeg'), logo: await dataURL(TITLE_FALLBACK.logo, 'image/png') })};\n`;
const out = await build({
  entryPoints: ['src/main.js'],
  bundle: true,
  format: 'esm',
  minify: true,
  target: 'es2022',
  write: false,
  legalComments: 'none',
  // 诊断面板里显示的版本号（构建时间 + 提交），用来确认手机上跑的是不是新版本
  define: { __JM_BUILD__: JSON.stringify(buildId()) },
  plugins:[{name:'phone-offline-assets',setup(b){
    b.onLoad({filter:/[\\/]fps[\\/]model-data\.js$/},()=>({contents:`export const FPS_MODEL_ASSETS = ${JSON.stringify(embeddedFPS)};`,loader:'js'}));
    b.onLoad({filter:/[\\/]props[\\/]prop-data\.js$/},()=>({contents:propModule,loader:'js'}));
    b.onLoad({filter:/[\\/]render[\\/]sky-data\.js$/},()=>({contents:skyModule,loader:'js'}));
    b.onLoad({filter:/[\\/]title[\\/]title-data\.js$/},()=>({contents:titleModule,loader:'js'}));
    b.onLoad({filter:/[\\/]title[\\/]fallback-data\.js$/},()=>({contents:fallbackModule,loader:'js'}));
  }}],
});
const code = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const threeLicense = await readFile('node_modules/three/LICENSE', 'utf8');
const peopleLicense = await readFile('assets/models/people/LICENSE.txt', 'utf8');
const geometryLicense = await geometryLicenses();
// 交付文件连 three.js 和材质一起内嵌；系统字体兜底，断网可用。
const offlineShell = shell.replace(/<link[^>]*https:\/\/fonts\.[^>]+>\s*/g, '')
  .replace(/<script type="importmap">[\s\S]*?<\/script>/, '');
const page = offlineShell.replace('<!--APP-->', () => `<!-- Three.js license\n${threeLicense}\n-->\n<!-- Microsoft Rocketbox avatar license\n${peopleLicense}\n-->\n<!-- Geometry library licenses\n${geometryLicense}\n-->\n<script type="module">${code}</script>`);

await mkdir('dist', { recursive: true });
await writeFile('dist/artifact.html', page);
await writeFile('dist/mall.html', wrap(page));

const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(0) + ' KB';
console.log(`index.html ok · dist/artifact.html ${kb(page)} · dist/mall.html ${kb(wrap(page))}`);

function wrap(body) {
  return (
    '<!doctype html>\n<html lang="zh-CN">\n<head>\n<meta charset="utf-8">\n' +
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n' +
    // 添加到主屏幕后全屏打开（iOS：独立应用 + 透明状态栏，内容铺到刘海 / 灵动岛下面）
    '<meta name="apple-mobile-web-app-capable" content="yes">\n<meta name="mobile-web-app-capable" content="yes">\n' +
    '<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">\n<meta name="apple-mobile-web-app-title" content="围城">\n' +
    '<meta name="theme-color" content="#070809">\n' +
    '</head>\n<body>\n' + body + '\n</body>\n</html>\n'
  );
}

function buildId() {
  let rev = 'nogit';
  try { rev = execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch { /* 没有 git 也能构建 */ }
  return `${new Date().toISOString().slice(0, 16).replace('T', ' ')} ${rev}`;
}
