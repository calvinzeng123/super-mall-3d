// 生成三个产物：
//   index.html          开发版，直接引用 ./src/main.js（需本地 http 服务）
//   dist/artifact.html  发布片段（无 doctype/head/body，供 Artifact 包装）
//   dist/mall.html      完整单文件页面，可双击打开
import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';

const shell = await readFile('src/shell.html', 'utf8');
if (!shell.includes('<!--APP-->')) throw new Error('src/shell.html 缺少 <!--APP--> 占位');

const manifest = JSON.parse(await readFile('assets/textures/manifest.json', 'utf8'));
const surfaces = await Promise.all(manifest.assets.map(async (asset) => ({
  id: asset.id, meters: asset.meters, sourceUrl: asset.sourceUrl,
  maps: Object.fromEntries(await Promise.all(Object.entries(asset.maps).map(async ([key, map]) =>
    [key, `data:image/jpeg;base64,${(await readFile(map.path)).toString('base64')}`]))),
})));
await writeFile('src/render/pbr-data.js', '// Generated by build.mjs from CC0 source assets.\nexport const SURFACE_ASSETS = ' + JSON.stringify(surfaces) + ';\n');
const peopleManifest = JSON.parse(await readFile('assets/models/people/manifest.json', 'utf8'));
const peopleAssets = await Promise.all(peopleManifest.models.map(async model => ({
  id: model.id, name: model.name, poses: model.poses, cycleSeconds: model.cycleSeconds,
  license: 'MIT', url: `data:model/gltf-binary;base64,${(await readFile(`assets/models/people/${model.file}`)).toString('base64')}`,
})));
await writeFile('src/render/people-data.js', '// Generated from MIT Microsoft Rocketbox models.\nexport const PEOPLE_ASSETS = ' + JSON.stringify(peopleAssets) + ';\n');
const suiteBytes = await readFile('assets/models/user-suite-processed.glb');
await writeFile('src/render/suite-data.js', '// Generated by build.mjs from the user suite model.\nexport const SUITE_MODEL_URL = ' + JSON.stringify(`data:model/gltf-binary;base64,${suiteBytes.toString('base64')}`) + ';\n');

// Preserve the original Blender exports byte-for-byte. Compression only changes
// their transport in the offline page; the loader still receives the same GLBs.
const residentialAssets = [];
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
for (const unit of ['01', '02', '03']) {
  const plan = JSON.parse(await readFile(`scripts/residential/plan_${unit}.json`, 'utf8'));
  const basename = plan.model_basename || `云澜汇_${unit}${unit === '03' ? '四' : '三'}房两厅`;
  const bytes = await readFile(`prototypes/residential${unit}/${basename}.glb`);
  if (bytes.readUInt32LE(0) !== 0x46546c67 || bytes.readUInt32LE(8) !== bytes.length) throw new Error(`住宅${unit} GLB不完整`);
  const jsonLength = bytes.readUInt32LE(12);
  const definition = JSON.parse(bytes.subarray(20, 20 + jsonLength).toString('utf8'));
  const binaryStart = 20 + jsonLength + 8;
  const imageHashes = definition.images.map(image => {
    const view = definition.bufferViews[image.bufferView];
    if (!view) throw new Error(`住宅${unit}包含非内嵌图片`);
    return sha256(bytes.subarray(binaryStart + (view.byteOffset || 0), binaryStart + (view.byteOffset || 0) + view.byteLength));
  });
  const compressed = gzipSync(bytes, { level: 6 });
  residentialAssets.push({ unit, compression: 'gzip', data: compressed.toString('base64'),
    modelFile: `${basename}.glb`, modelSHA256: sha256(bytes), modelBytes: bytes.length,
    compressedBytes: compressed.length, compressedSHA256: sha256(compressed), imageHashes,
    textureSources: definition.textures.map(texture => texture.source),
    width: plan.envelope.outer_rect[2], depth: plan.envelope.outer_rect[3], ceiling: plan.envelope.ceiling_z,
    lighting: plan.viewer?.lighting || null });
}
await writeFile('src/render/residential-data.js', '// Generated by build.mjs from the original residential GLBs. Do not edit.\nexport const RESIDENTIAL_ASSETS = ' + JSON.stringify(residentialAssets) + ';\n');

await writeFile('index.html', wrap(shell.replace('<!--APP-->', '<script type="module" src="./src/main.js"></script>')));

const out = await build({
  entryPoints: ['src/main.js'],
  bundle: true,
  format: 'esm',
  minify: true,
  target: 'es2022',
  write: false,
  legalComments: 'none',
});
const code = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const threeLicense = await readFile('node_modules/three/LICENSE', 'utf8');
const peopleLicense = await readFile('assets/models/people/LICENSE.txt', 'utf8');
// 交付文件连 three.js 和材质一起内嵌；系统字体兜底，断网可用。
const offlineShell = shell.replace(/<link[^>]*https:\/\/fonts\.[^>]+>\s*/g, '')
  .replace(/<script type="importmap">[\s\S]*?<\/script>/, '');
const page = offlineShell.replace('<!--APP-->', () => `<!-- Three.js license\n${threeLicense}\n-->\n<!-- Microsoft Rocketbox avatar license\n${peopleLicense}\n-->\n<script type="module">${code}</script>`);

await mkdir('dist', { recursive: true });
await writeFile('dist/artifact.html', page);
await writeFile('dist/mall.html', wrap(page));

const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(0) + ' KB';
console.log(`index.html ok · dist/artifact.html ${kb(page)} · dist/mall.html ${kb(wrap(page))}`);

function wrap(body) {
  return (
    '<!doctype html>\n<html lang="zh-CN">\n<head>\n<meta charset="utf-8">\n' +
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n' +
    '</head>\n<body>\n' + body + '\n</body>\n</html>\n'
  );
}
